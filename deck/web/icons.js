// Struck-through variants: the icon with a diagonal line, cleared either side so it reads.
function slashed(rows) {
  return rows.map((row, y) =>
    [...row].map((c, x) => (x === y ? "#" : Math.abs(x - y) === 1 ? "." : c)).join(""),
  );
}
I.micoff = slashed(I.mic);
I.hide = slashed(I.eye);

export const ICONS = I;
export const ICON_NAMES = Object.keys(I);

/** An SVG of the icon's dots. `off` draws the unlit dots too, in that colour. */
export function dotIcon(name, { off = null, cls = "ic" } = {}) {
  const rows = I[name];
  if (!rows) return "";
  let dots = "";
  for (let y = 0; y < 9; y++) {
    const row = rows[y] || "";
    for (let x = 0; x < 9; x++) {
      const lit = row[x] === "#";
      if (lit) dots += `<circle cx="${x + 0.5}" cy="${y + 0.5}" r=".4"/>`;
      else if (off) dots += `<circle cx="${x + 0.5}" cy="${y + 0.5}" r=".4" fill="${off}"/>`;
    }
  }
  return `<svg class="${cls}" viewBox="0 0 9 9" fill="currentColor" aria-hidden="true">${dots}</svg>`;
}
